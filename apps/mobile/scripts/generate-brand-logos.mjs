// Bundles the web's operator logos into the app, with the web's brand names and aliases.
// Run `pnpm --filter=mobile generate:brand-logos` after changing the web's brands or logos.
import { access, mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { format } from "oxfmt";
import sharp from "sharp";
import ts from "typescript";

const source = new URL("../../web/src/components/brands.tsx", import.meta.url);
const logosDir = new URL("../../web/public/assets/operators/", import.meta.url);
const output = new URL("../src/lib/brands.ts", import.meta.url);
const logosImportPath = "../../../web/public/assets/operators";
const operatorAssets = new URL("../assets/generated/operator-logos/", import.meta.url);

const code = await readFile(source, "utf8");
const sourceFile = ts.createSourceFile(
  source.pathname,
  code,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX,
);

function readObject(name) {
  const declaration = sourceFile.statements
    .filter(ts.isVariableStatement)
    .flatMap((statement) => [...statement.declarationList.declarations])
    .find((entry) => ts.isIdentifier(entry.name) && entry.name.text === name);
  const object = declaration?.initializer;
  if (!object || !ts.isObjectLiteralExpression(object)) {
    throw new Error(`${name} not found in ${source.pathname}`);
  }
  return Object.fromEntries(
    object.properties.map((property) => {
      if (
        !ts.isPropertyAssignment(property) ||
        !(ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) ||
        !ts.isStringLiteral(property.initializer)
      ) {
        throw new Error(`${name} must contain only literal string mappings.`);
      }
      return [property.name.text, property.initializer.text];
    }),
  );
}

const brandPaths = readObject("brandPaths");
const brandAliases = readObject("brandAliases");
const operators = JSON.parse(
  await readFile(new URL("../../../packages/data/src/operators.json", import.meta.url), "utf8"),
);
const lines = JSON.parse(
  await readFile(new URL("../../../packages/data/src/lines.json", import.meta.url), "utf8"),
);
const lineOperators = new Set(lines.map((line) => line.operator));
const operatorPaths = Object.fromEntries(
  operators
    .filter((operator) => lineOperators.has(operator.slug) && operator.logoPath)
    .map((operator) => [operator.slug, operator.logoPath]),
);
const paths = [...new Set(Object.values(brandPaths))].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const allPaths = new Set([...paths, ...Object.values(operatorPaths)]);

for (const path of allPaths) {
  await access(new URL(`${path}.svg`, logosDir)).catch(() => {
    throw new Error(`Logo ${path}.svg is missing in ${logosDir.pathname}`);
  });
}

// Static operator icons follow the country flags' density variants. Rasterizing the existing
// SVGs also keeps editor-specific metadata out of native JSX without changing the web artwork.
if (!process.argv.includes("--check")) {
  await mkdir(operatorAssets, { recursive: true });
  for (const [slug, path] of Object.entries(operatorPaths)) {
    const svg = await readFile(new URL(`${path}.svg`, logosDir), "utf8");
    // SVG renderers don't paint the CSS canvas background. Preserve it explicitly so white
    // marks such as RBS and Luas stay visible on their original colored background.
    const attributes = svg.match(/<svg\b([^>]*)>/is)?.[1];
    const style = attributes?.match(/\sstyle=(["'])(.*?)\1/is)?.[2];
    const background =
      style?.match(/(?:^|;)\s*background(?:-color)?\s*:\s*([^;]+)/i)?.[1]?.trim() ?? "#fff";
    for (const scale of [1, 2, 3]) {
      const pixels = 24 * scale;
      const image = await sharp(Buffer.from(svg), { density: 72 * scale })
        .resize(pixels, pixels)
        .flatten({ background })
        .png()
        .toBuffer();
      const suffix = scale === 1 ? "" : `@${scale}x`;
      const target = new URL(`${slug}${suffix}.png`, operatorAssets);
      const existing = await readFile(target).catch((error) => {
        if (error.code !== "ENOENT") throw error;
        return null;
      });
      if (existing?.equals(image)) continue;
      const temporary = new URL(`${slug}${suffix}.${process.pid}.tmp`, operatorAssets);
      await writeFile(temporary, image);
      await rename(temporary, target);
    }
  }
}

const key = (value) => (/^[a-z_$][\w$]*$/i.test(value) ? value : JSON.stringify(value));
const entries = (object, format) =>
  Object.entries(object)
    .map(([name, value]) => `  ${key(name)}: ${format(value)},`)
    .join("\n");

const generated = `// Generated by scripts/generate-brand-logos.mjs from web brands and bundled line operators.
// Refreshed automatically when Metro starts. Do not edit by hand.
import type { FC } from "react";
import type { ImageSourcePropType } from "react-native";
import type { SvgProps } from "react-native-svg";

type Logo = FC<SvgProps>;

// The web's logos, compiled into native SVG components at build time. Each one is
// only loaded the first time a board shows it.
const logos: Record<string, () => Logo> = {
${paths.map((path) => `  ${JSON.stringify(path)}: () => require("${logosImportPath}/${path}.svg").default,`).join("\n")}
};

const brandPaths: Record<string, string> = {
${entries(brandPaths, JSON.stringify)}
};

// Brands that share another brand's logo.
const brandAliases: Record<string, string> = {
${entries(brandAliases, JSON.stringify)}
};

// Operator slugs are independent of the live boards' brand names and aliases.
const operatorLogos: Record<string, () => ImageSourcePropType> = {
${Object.keys(operatorPaths)
  .map(
    (slug) => `  ${key(slug)}: () => require("../../assets/generated/operator-logos/${slug}.png"),`,
  )
  .join("\n")}
};

/** A bundled line operator's logo, or null when artwork isn't available. */
export function getOperatorLogo(operator: string | null): ImageSourcePropType | null {
  return operator && Object.hasOwn(operatorLogos, operator) ? operatorLogos[operator]!() : null;
}

/** The brand's logo, or null when it has none. */
export function getBrandLogo(brand: string): Logo | null {
  const normalized = brand.trim().toLowerCase();
  const canonical = Object.hasOwn(brandAliases, normalized) ? brandAliases[normalized]! : normalized;
  const path = Object.hasOwn(brandPaths, canonical) ? brandPaths[canonical] : null;
  return path ? (logos[path]?.() ?? null) : null;
}
`;
const formatted = await format(output.pathname, generated);
if (formatted.errors.length > 0) throw new Error("Could not format the generated brand registry.");
const previous = await readFile(output, "utf8").catch(() => null);
if (process.argv.includes("--check")) {
  if (previous !== formatted.code) {
    throw new Error("Mobile brand logos are stale. Run pnpm --filter=mobile generate:brand-logos.");
  }
} else if (previous !== formatted.code) {
  await writeFile(output, formatted.code);
}

console.log(
  `Validated ${allPaths.size} logos, ${Object.keys(brandPaths).length} brands and ${Object.keys(operatorPaths).length} line operators.`,
);
